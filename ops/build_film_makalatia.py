def main():
    narration = " ".join(s for _, s in SEGMENTS)
    scenes = []
    for sc, sentence in SEGMENTS:
        words = sentence.split()
        at = " ".join(words[:5]) if len(words) >= 5 else sentence
        assert narration.count(at) == 1, (at, narration.count(at))
        sc = dict(sc)
        sc["at"] = at
        scenes.append(sc)
    scenes.sort(key=lambda x: narration.find(x["at"]))
    pos = [narration.find(s["at"]) for s in scenes]
    assert pos == sorted(pos) and all(p >= 0 for p in pos), pos
    story = {
        "id": 900020,
        "lang": "ka",
        "category": "politics",
        "date": "2026-11-04T20:00:00+04:00",
        "url": "https://tbilisi.today/",
        "sources": ["საჯარო რეესტრი", "საქსტატი", "companyinfo.ge"],
        "private": True,
        "narration": narration,
        "scenes": scenes,
        "say": {},
    }
    OUT.write_text(json.dumps(story, ensure_ascii=False, indent=1))
    print("words", len(narration.split()), "scenes", len(scenes), "->", OUT)


if __name__ == "__main__":
    main()
